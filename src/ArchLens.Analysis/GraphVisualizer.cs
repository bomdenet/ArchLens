using System.Text;
using ArchLens.Model;

namespace ArchLens.Analysis;

/// <summary>
/// Exports a CodeGraph to human-readable diagram formats: Mermaid, Graphviz DOT, and Structurizr DSL.
/// Highlights dependency cycles clearly and respects filter/maxNodes limits.
/// </summary>
public static class GraphVisualizer
{
    public static string Export(
        CodeGraph graph,
        string format,
        NodeKind scope = NodeKind.Namespace,
        string? filterPattern = null,
        int maxNodes = 60) => format.Trim().ToLowerInvariant() switch
        {
            "mermaid" or "mmd" => ExportMermaid(graph, scope, filterPattern, maxNodes),
            "dot" or "graphviz" => ExportDot(graph, scope, filterPattern, maxNodes),
            "structurizr" or "dsl" => ExportStructurizrDsl(graph, scope, filterPattern, maxNodes),
            _ => throw new ArgumentException($"Unsupported diagram format '{format}'. Supported formats: mermaid, dot, structurizr.", nameof(format))
        };

    public static string ExportMermaid(
        CodeGraph graph,
        NodeKind scope = NodeKind.Namespace,
        string? filterPattern = null,
        int maxNodes = 60)
    {
        var (nodes, edges, cycleEdges, totalMatching) = PrepareSubgraph(graph, scope, filterPattern, maxNodes);
        var idMap = BuildSafeIdMap(nodes, prefix: "N");

        var sb = new StringBuilder();
        sb.AppendLine("flowchart LR");
        if (totalMatching > nodes.Count)
        {
            sb.Append("  %% Showing ").Append(nodes.Count).Append(" of ").Append(totalMatching)
              .Append(" matching ").Append(scope.ToString().ToLowerInvariant())
              .Append(" nodes (truncated by maxNodes=").Append(Math.Max(1, maxNodes)).AppendLine(")");
        }

        foreach (var node in nodes)
        {
            sb.Append("  ").Append(idMap[node]).Append("[\"").Append(EscapeMermaid(node)).AppendLine("\"]");
        }

        var cycleLinkIndices = new List<int>();
        for (var i = 0; i < edges.Count; i++)
        {
            var (from, to) = edges[i];
            var isCycle = cycleEdges.Contains((from, to));
            var arrow = isCycle ? "==>" : "-->";
            sb.Append("  ").Append(idMap[from]).Append(' ').Append(arrow).Append(' ').AppendLine(idMap[to]);
            if (isCycle)
            {
                cycleLinkIndices.Add(i);
            }
        }

        foreach (var idx in cycleLinkIndices)
        {
            sb.Append("  linkStyle ").Append(idx).AppendLine(" stroke:#dc2626,stroke-width:2px");
        }

        return sb.ToString();
    }

    public static string ExportDot(
        CodeGraph graph,
        NodeKind scope = NodeKind.Namespace,
        string? filterPattern = null,
        int maxNodes = 60)
    {
        var (nodes, edges, cycleEdges, totalMatching) = PrepareSubgraph(graph, scope, filterPattern, maxNodes);
        var idMap = BuildSafeIdMap(nodes, prefix: "n");
        var cycleNodes = cycleEdges.SelectMany(e => new[] { e.From, e.To }).ToHashSet(StringComparer.Ordinal);

        var sb = new StringBuilder();
        sb.AppendLine("digraph ArchLens {");
        if (totalMatching > nodes.Count)
        {
            sb.Append("  // Showing ").Append(nodes.Count).Append(" of ").Append(totalMatching)
              .Append(" matching ").Append(scope.ToString().ToLowerInvariant())
              .Append(" nodes (truncated by maxNodes=").Append(Math.Max(1, maxNodes)).AppendLine(")");
        }
        sb.AppendLine("  rankdir=LR;");
        sb.AppendLine("  node [shape=box, style=\"rounded,filled\", fillcolor=\"#f8fafc\", color=\"#64748b\", fontname=\"Segoe UI\"];");
        sb.AppendLine("  edge [color=\"#475569\"];");

        foreach (var node in nodes)
        {
            var extra = cycleNodes.Contains(node) ? ", fillcolor=\"#fee2e2\", color=\"#dc2626\"" : string.Empty;
            sb.Append("  ").Append(idMap[node]).Append(" [label=\"").Append(EscapeDot(node)).Append('"').Append(extra).AppendLine("];");
        }

        foreach (var (from, to) in edges)
        {
            var style = cycleEdges.Contains((from, to)) ? " [color=\"#dc2626\", penwidth=2]" : string.Empty;
            sb.Append("  ").Append(idMap[from]).Append(" -> ").Append(idMap[to]).Append(style).AppendLine(";");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    public static string ExportStructurizrDsl(
        CodeGraph graph,
        NodeKind scope = NodeKind.Namespace,
        string? filterPattern = null,
        int maxNodes = 60)
    {
        var (nodes, edges, cycleEdges, totalMatching) = PrepareSubgraph(graph, scope, filterPattern, maxNodes);
        var idMap = BuildSafeIdMap(nodes, prefix: "el");

        var sb = new StringBuilder();
        sb.AppendLine("workspace \"ArchLens Architecture\" \"Generated by ArchLens\" {");
        if (totalMatching > nodes.Count)
        {
            sb.Append("  // Showing ").Append(nodes.Count).Append(" of ").Append(totalMatching)
              .Append(" matching ").Append(scope.ToString().ToLowerInvariant())
              .Append(" nodes (truncated by maxNodes=").Append(Math.Max(1, maxNodes)).AppendLine(")");
        }
        sb.AppendLine("  model {");
        sb.AppendLine("    sys = softwareSystem \"Analyzed Solution\" {");

        if (scope == NodeKind.Project)
        {
            foreach (var node in nodes)
            {
                sb.Append("      ").Append(idMap[node]).Append(" = container \"").Append(EscapeStructurizr(node)).AppendLine("\" \"\" \".NET Project\"");
            }
        }
        else
        {
            sb.AppendLine("      app = container \"Solution\" \"\" \".NET\" {");
            foreach (var node in nodes)
            {
                sb.Append("        ").Append(idMap[node]).Append(" = component \"").Append(EscapeStructurizr(node)).Append("\" \"\" \"").Append(scope).AppendLine("\"");
            }
            sb.AppendLine("      }");
        }

        sb.AppendLine("    }");
        sb.AppendLine();

        foreach (var (from, to) in edges)
        {
            if (cycleEdges.Contains((from, to)))
            {
                sb.Append("    ").Append(idMap[from]).Append(" -> ").Append(idMap[to]).AppendLine(" \"depends on (cycle)\" \"\" \"Cycle\"");
            }
            else
            {
                sb.Append("    ").Append(idMap[from]).Append(" -> ").Append(idMap[to]).AppendLine(" \"depends on\"");
            }
        }

        sb.AppendLine("  }");
        sb.AppendLine("  views {");
        if (scope == NodeKind.Project)
        {
            sb.AppendLine("    container sys \"Containers\" {");
            sb.AppendLine("      include *");
            sb.AppendLine("      autoLayout");
            sb.AppendLine("    }");
        }
        else
        {
            sb.AppendLine("    component app \"Components\" {");
            sb.AppendLine("      include *");
            sb.AppendLine("      autoLayout");
            sb.AppendLine("    }");
        }

        if (cycleEdges.Count > 0)
        {
            sb.AppendLine("    styles {");
            sb.AppendLine("      relationship \"Cycle\" {");
            sb.AppendLine("        color #dc2626");
            sb.AppendLine("        thickness 3");
            sb.AppendLine("      }");
            sb.AppendLine("    }");
        }

        sb.AppendLine("  }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static (List<string> Nodes, List<(string From, string To)> Edges, HashSet<(string From, string To)> CycleEdges, int TotalMatchingNodes) PrepareSubgraph(
        CodeGraph graph,
        NodeKind scope,
        string? filterPattern,
        int maxNodes)
    {
        var adj = graph.BuildAdjacency(scope);
        var cycles = CycleDetector.FindCycles(graph, scope);

        var matchingNodes = adj.Keys
            .Where(k => GlobMatcher.IsMatch(k, filterPattern))
            .OrderByDescending(k => adj[k].Count)
            .ThenBy(k => k, StringComparer.Ordinal)
            .ToList();
        var selectedNodes = matchingNodes
            .Take(Math.Max(1, maxNodes))
            .OrderBy(k => k, StringComparer.Ordinal)
            .ToList();

        var selectedSet = selectedNodes.ToHashSet(StringComparer.Ordinal);
        var edges = new List<(string From, string To)>();

        foreach (var from in selectedNodes)
        {
            foreach (var to in adj[from].OrderBy(x => x, StringComparer.Ordinal))
            {
                if (selectedSet.Contains(to))
                {
                    edges.Add((from, to));
                }
            }
        }

        var cycleEdges = new HashSet<(string From, string To)>();
        foreach (var cycle in cycles)
        {
            var members = cycle.Nodes.ToHashSet(StringComparer.Ordinal);
            foreach (var (from, to) in edges)
            {
                if (members.Contains(from) && members.Contains(to))
                {
                    cycleEdges.Add((from, to));
                }
            }
        }

        return (selectedNodes, edges, cycleEdges, matchingNodes.Count);
    }

    private static Dictionary<string, string> BuildSafeIdMap(List<string> nodes, string prefix)
    {
        var map = new Dictionary<string, string>(StringComparer.Ordinal);
        for (var i = 0; i < nodes.Count; i++)
        {
            map[nodes[i]] = $"{prefix}{i + 1}";
        }
        return map;
    }

    private static string EscapeMermaid(string text) =>
        text.Replace("&", "&amp;")
            .Replace("#", "&#35;")
            .Replace("<", "&lt;")
            .Replace(">", "&gt;")
            .Replace("\"", "&quot;")
            .Replace("`", "&#96;")
            .Replace("\r", " ")
            .Replace("\n", " ");

    private static string EscapeDot(string text) =>
        text.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", " ").Replace("\n", " ");

    private static string EscapeStructurizr(string text) =>
        text.Replace("\"", "'").Replace("\r", " ").Replace("\n", " ");
}
